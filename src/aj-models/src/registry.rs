//! Model metadata, registry, and catalog loading.
//!
//! Defines the static catalog of known models and the lookup surface used
//! by the rest of the codebase. The registry has no runtime network
//! dependency: it is populated at startup from a JSON catalog, either the
//! bundled seed compiled into the binary via `include_str!` or an
//! optional user cache at `~/.aj/models.json` written by the catalog
//! refresh CLI. Overrides from the bundled `overrides.json` are applied
//! on top of whichever catalog loads, so authored corrections survive
//! refreshes.

use std::collections::HashMap;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use crate::types::{ThinkingLevel, Usage};

/// Bundled seed, generated by the catalog refresh process. Always
/// present; guarantees the registry loads on first run, offline, or when
/// models.dev is unreachable. Updated by running the refresh command and
/// committing the resulting JSON.
const SEED_MODELS_JSON: &str = include_str!("../data/models.json");

/// Bundled overrides: shallow patches that correct known upstream
/// inaccuracies in the catalog, applied on every load (seed and user
/// cache alike). Currently empty; kept as the seam for authored
/// corrections when a source ships wrong data.
const OVERRIDES_JSON: &str = include_str!("../data/overrides.json");

/// Bundled OpenAI Codex seed. The `openai-codex` provider points at
/// the ChatGPT subscription backend (`chatgpt.com/backend-api`) and
/// is not enumerated by models.dev, so its model list is maintained
/// here alongside the overrides file. The list is
/// authoritative: refresh appends these entries to every fresh cache
/// (defensively filtering any upstream re-emission first), and load
/// splices them in so users on a stale cache or an older bundled seed
/// still see Codex models. Limits, pricing, and reasoning controls are
/// hand-curated from the Codex CLI's own model catalog (the ChatGPT
/// backend advertises no `none`/`minimal` effort, so those rungs are
/// intentionally absent), not from models.dev whose API entries carry a
/// different effort vocabulary.
const CODEX_SEED_JSON: &str = include_str!("../data/codex.json");

/// Provider id used to key Codex catalog entries. Exposed so the
/// refresh and load paths agree on the value used for filtering and
/// splicing.
pub const CODEX_PROVIDER_ID: &str = "openai-codex";

/// Maximum allowed catalog age before the registry warns the user.
/// 90 days is a compromise — pricing changes on the order of months and
/// new models ship every few weeks; tighter thresholds would warn too
/// often on stable catalogs.
const STALENESS_THRESHOLD_DAYS: i64 = 90;

// ============================================================================
// Model Metadata
// ============================================================================

/// Supported input modality. Matches the lowercase string form used by
/// the catalog JSON ("text" / "image").
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum InputModality {
    Text,
    Image,
}

/// A reasoning control a model exposes, mirroring the catalog source's
/// `reasoning_options` shape. Drives the thinking levels AJ offers and
/// validates, and (for Anthropic) whether the adaptive thinking API is
/// used. Refresh normalizes each source's vocabulary into this form.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ReasoningOption {
    /// Reasoning can be turned on or off, with no effort selection.
    Toggle,
    /// Reasoning effort is chosen from a fixed vocabulary. A
    /// [`ThinkingLevel::Off`] value means the model accepts an explicit
    /// "no reasoning" effort (upstream `"none"`).
    Effort { values: Vec<ThinkingLevel> },
    /// Reasoning is controlled by a token budget within `[min, max]`.
    /// Either bound may be absent when the source doesn't publish it.
    BudgetTokens {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        min: Option<u64>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        max: Option<u64>,
    },
}

/// Per-million-token cost rates for a model.
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
pub struct ModelCost {
    pub input: f64,
    pub output: f64,
    pub cache_read: f64,
    pub cache_write: f64,
    /// Context-based pricing tiers. Empty for flat-rate models.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tiers: Vec<ModelCostTier>,
}

/// A context-based pricing tier: a step function that replaces the base
/// [`ModelCost`] rates for the whole request once the request is large
/// enough. Tiers are not marginal, the selected tier's rates apply to
/// every token category of the entire request.
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
pub struct ModelCostTier {
    /// Total input-side token threshold for this tier, compared against
    /// `input + cache_read + cache_write` of the request's usage. The
    /// tier applies when the total input-side usage is strictly greater
    /// than this value. Among all tiers that apply, the one with the
    /// largest `input_tokens_above` wins and its rates replace the base
    /// rates for the whole request. If two tiers share a threshold the
    /// later one in the list wins, but well-formed data has no such ties.
    pub input_tokens_above: u64,
    pub input: f64,
    pub output: f64,
    pub cache_read: f64,
    pub cache_write: f64,
}

/// Static metadata for a known model. Each entry is the result of
/// merging a catalog entry with any matching overrides.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct ModelInfo {
    /// Model identifier sent to the API (e.g. "claude-sonnet-4-20250514").
    pub id: String,
    /// Human-readable name (e.g. "Claude Sonnet 4").
    pub name: String,
    /// API type. One of "anthropic-messages", "openai-completions", or
    /// "openai-responses". Each `(provider, id)` pair has exactly one
    /// `api` — there is no duplication.
    pub api: String,
    /// Provider name (e.g. "anthropic", "openai").
    pub provider: String,
    /// Base URL for API requests.
    pub base_url: String,
    /// Whether the model supports extended thinking / reasoning.
    pub reasoning: bool,
    /// The reasoning controls this model exposes, as published by the
    /// catalog source. Empty for non-reasoning models, and for
    /// reasoning models whose source advertises no verified control.
    /// Drives the thinking levels AJ offers and validates, and (via
    /// [`supports_adaptive_thinking`]) whether an Anthropic model uses
    /// the adaptive thinking API.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub reasoning_options: Vec<ReasoningOption>,
    /// Whether the model honours OpenAI's `text.verbosity` parameter
    /// (the answer-length knob, see [`crate::types::Verbosity`]). The
    /// gpt-5 family on the Responses / Codex wire supports it; older
    /// OpenAI models and non-OpenAI models do not. Gates whether a
    /// caller-set verbosity reaches the request: unsupported models
    /// silently ignore the knob rather than 400.
    ///
    /// Not in models.dev. Derived in the refresh mapper (the OpenAI
    /// gpt-5 family on `openai-responses`, and OpenRouter's
    /// `supported_parameters`), hand-set on the Codex seed, and
    /// pinnable per model via overrides. The serde default is `false`.
    #[serde(default)]
    pub supports_verbosity: bool,
    /// Supported input modalities.
    pub input: Vec<InputModality>,
    /// Pricing per million tokens.
    pub cost: ModelCost,
    /// Maximum context window in tokens.
    pub context_window: u64,
    /// Maximum output tokens.
    pub max_tokens: u64,
}

// ============================================================================
// Catalog file schema
// ============================================================================

/// Current on-disk catalog schema version. Bump it whenever the bundled
/// catalog must supersede an existing user cache: when [`ModelInfo`]'s
/// shape changes in a way that would load older caches with
/// silently-wrong data, or when the bundled seed carries corrected data
/// that the additive load-time Codex splice can't push into a cache that
/// already holds those entries. A user cache whose `schema_version`
/// differs is ignored in favour of the bundled seed (see
/// [`load_active_catalog`]), so an incompatible or stale cache is a clean
/// miss rather than a subtle bug.
pub const CATALOG_SCHEMA_VERSION: u32 = 2;

/// On-disk catalog format shared by the bundled seed and the user cache.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Catalog {
    /// Schema version of this file. Absent in pre-versioned caches, so
    /// the serde default of `0` never equals [`CATALOG_SCHEMA_VERSION`]
    /// and those caches are rejected on load.
    #[serde(default)]
    pub schema_version: u32,
    /// Unix milliseconds when the catalog was last refreshed. Drives the
    /// staleness warning.
    pub updated_at: i64,
    /// Origin label (e.g. "models.dev"). Free-form; informational.
    pub source: String,
    pub models: Vec<ModelInfo>,
}

// ============================================================================
// Overrides file schema
// ============================================================================

/// On-disk overrides file. Each entry targets one `(provider, id)` pair
/// and shallow-merges the patch fields onto the matched model.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct OverridesFile {
    pub overrides: Vec<OverrideEntry>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct OverrideEntry {
    pub target: OverrideTarget,
    pub patch: OverridePatch,
    /// Required free-form rationale; surfaces to anyone reviewing the
    /// overrides file later.
    pub reason: String,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct OverrideTarget {
    pub provider: String,
    pub id: String,
}

/// Shallow-merge patch over a [`ModelInfo`]. Each `Option` is leave-alone
/// when `None` and replace-whole when `Some`. Nested objects (`cost`,
/// `input`) are replaced wholesale, not deep-merged — predictable wins
/// over clever.
#[derive(Serialize, Deserialize, Clone, Debug, Default)]
pub struct OverridePatch {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub api: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub base_url: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning: Option<bool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_options: Option<Vec<ReasoningOption>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub supports_verbosity: Option<bool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub input: Option<Vec<InputModality>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cost: Option<ModelCost>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub context_window: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_tokens: Option<u64>,
}

