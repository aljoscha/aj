/// Structural equality of two models by `(provider, api, id)`. Two
/// `ModelInfo`s with identical identity but different metadata still
/// compare equal — identity, not state, is what cross-provider replay
/// cares about.
pub fn models_are_equal(a: &ModelInfo, b: &ModelInfo) -> bool {
    a.provider == b.provider && a.api == b.api && a.id == b.id
}

/// Whether the model uses Anthropic's adaptive thinking API
/// (`thinking: {type: "adaptive"}` + `output_config: {effort}`) rather
/// than budget-based thinking.
///
/// Derived: an Anthropic model that advertises an [`ReasoningOption::Effort`]
/// control. A model that only exposes a budget control (legacy
/// Anthropic) is budget-based. This also gates the
/// `interleaved-thinking-2025-05-14` beta, which adaptive models reject
/// or ignore.
pub fn supports_adaptive_thinking(model: &ModelInfo) -> bool {
    model.api == "anthropic-messages"
        && model
            .reasoning_options
            .iter()
            .any(|o| matches!(o, ReasoningOption::Effort { .. }))
}

/// Whether the model honours OpenAI's `text.verbosity` parameter.
/// Thin accessor over [`ModelInfo::supports_verbosity`].
pub fn supports_verbosity(model: &ModelInfo) -> bool {
    model.supports_verbosity
}

/// Validate a requested [`ThinkingLevel`] against a model's wire
/// vocabulary, returning a human-readable message when the level isn't
/// one the model offers.
///
/// aj sends the chosen effort verbatim, with no remapping, flooring, or
/// ceiling, so the level must be a member of
/// [`supported_thinking_levels`] for this model. A non-reasoning model
/// offers only `off`, and asking for any effort on it is an error rather
/// than a silent no-op.
pub fn validate_thinking_level(model: &ModelInfo, level: &ThinkingLevel) -> Result<(), String> {
    let supported = supported_thinking_levels(model);
    if supported.contains(level) {
        return Ok(());
    }
    let offered = supported
        .iter()
        .map(ThinkingLevel::as_str)
        .collect::<Vec<_>>()
        .join(", ");
    Err(format!(
        "model '{}' does not support thinking level '{}'; supported: {offered}",
        model.id,
        level.as_str(),
    ))
}

/// Every thinking level in canonical, cheapest-first order. Offered sets
/// are returned as a subset of this, so callers get a stable order.
const ALL_THINKING_LEVELS: [ThinkingLevel; 7] = [
    ThinkingLevel::Off,
    ThinkingLevel::Minimal,
    ThinkingLevel::Low,
    ThinkingLevel::Medium,
    ThinkingLevel::High,
    ThinkingLevel::XHigh,
    ThinkingLevel::Max,
];

/// The exact thinking levels a model offers, in canonical order. This is
/// the single source of truth for both the selector UI and
/// [`validate_thinking_level`].
///
/// The rules, in order:
///
/// - A non-reasoning model offers only `off`.
/// - An `Effort` control contributes its advertised levels verbatim, and
///   a `Toggle` control contributes `off`.
/// - Anthropic extended thinking is opt-in, so every reasoning Anthropic
///   model can also run with thinking `off`, regardless of its effort
///   enum (which names only the levels used while thinking is on).
/// - A reasoning model with no `Effort` control (budget-only,
///   toggle-only, or no controls at all) has no effort vocabulary to be
///   exact about, so it falls back to the full ladder and lets the
///   provider surface any level it can't honour.
pub fn supported_thinking_levels(model: &ModelInfo) -> Vec<ThinkingLevel> {
    if !model.reasoning {
        return vec![ThinkingLevel::Off];
    }

    let mut offered: Vec<ThinkingLevel> = Vec::new();
    let mut has_effort = false;
    for option in &model.reasoning_options {
        match option {
            ReasoningOption::Effort { values } => {
                has_effort = true;
                offered.extend(values.iter().copied());
            }
            ReasoningOption::Toggle => offered.push(ThinkingLevel::Off),
            // A token budget accepts any effort; the no-effort fallback
            // below turns that into the full ladder.
            ReasoningOption::BudgetTokens { .. } => {}
        }
    }

    if model.api == "anthropic-messages" {
        offered.push(ThinkingLevel::Off);
    }

    // No effort vocabulary to be exact about (budget-only, toggle-only,
    // or no controls at all): offer the full ladder.
    if !has_effort {
        return ALL_THINKING_LEVELS.to_vec();
    }

    let levels: Vec<ThinkingLevel> = ALL_THINKING_LEVELS
        .iter()
        .copied()
        .filter(|level| offered.contains(level))
        .collect();
    // An effort control normally maps at least one level, but an empty
    // or all-unknown effort enum (only reachable via a hand-edited
    // override) would leave nothing. Fall back to the full ladder so the
    // returned set is never empty and reasoning stays reachable.
    if levels.is_empty() {
        return ALL_THINKING_LEVELS.to_vec();
    }
    levels
}

// ============================================================================
// Catalog loading internals
// ============================================================================

/// Pick the active catalog, in priority order:
///
/// 1. User cache at `~/.aj/models.json` if present and parseable.
/// 2. Bundled seed (always succeeds — a malformed seed is a build-time
///    bug we surface via panic).
///
/// A user cache that exists but fails to parse logs a warning and falls
/// through to the seed. A missing cache falls through silently.
fn load_active_catalog() -> (Catalog, String) {
    if let Some(path) = user_cache_path()
        && path.exists()
    {
        match std::fs::read_to_string(&path) {
            Ok(body) => match serde_json::from_str::<Catalog>(&body) {
                Ok(cat) if cat.schema_version == CATALOG_SCHEMA_VERSION => {
                    return (cat, format!("user cache {}", path.display()));
                }
                Ok(cat) => tracing::warn!(
                    "user catalog at {} has schema version {} (expected {}); \
                     falling back to bundled seed (run `aj update-models` to refresh)",
                    path.display(),
                    cat.schema_version,
                    CATALOG_SCHEMA_VERSION
                ),
                Err(err) => tracing::warn!(
                    "failed to parse user catalog at {}: {err}; falling back to bundled seed",
                    path.display()
                ),
            },
            Err(err) => tracing::warn!(
                "failed to read user catalog at {}: {err}; falling back to bundled seed",
                path.display()
            ),
        }
    }

    let seed: Catalog = serde_json::from_str(SEED_MODELS_JSON)
        .expect("bundled models.json must be valid; check src/aj-models/data/models.json");
    (seed, "bundled seed".to_string())
}

/// Parse the bundled overrides. Failure here is non-fatal: we log a
/// warning and proceed with no overrides, so a malformed file at most
/// degrades cost/capability accuracy without bricking the registry.
pub fn bundled_overrides() -> OverridesFile {
    serde_json::from_str(OVERRIDES_JSON).unwrap_or_else(|err| {
        tracing::warn!("failed to parse bundled overrides.json: {err}; ignoring");
        OverridesFile { overrides: vec![] }
    })
}

/// On-disk shape of the bundled Codex seed file. Lives in its own
/// struct so the catalog and seed files don't share the
/// `updated_at`/`source` framing — the Codex list has no upstream and
/// no refresh timestamp.
#[derive(Serialize, Deserialize, Clone, Debug, Default)]
pub struct CodexSeedFile {
    pub models: Vec<ModelInfo>,
}

/// Parse the bundled OpenAI Codex seed (`data/codex.json`). Failure
/// here is non-fatal: we log a warning and proceed with an empty list,
/// so a malformed file at most hides Codex models without bricking the
/// registry. Each entry must already carry
/// `provider == CODEX_PROVIDER_ID`; non-Codex entries are dropped with
/// a warning so the file can't accidentally inject other providers.
pub fn bundled_codex_seed() -> Vec<ModelInfo> {
    let parsed: CodexSeedFile = match serde_json::from_str(CODEX_SEED_JSON) {
        Ok(file) => file,
        Err(err) => {
            tracing::warn!("failed to parse bundled codex.json: {err}; ignoring");
            return Vec::new();
        }
    };
    parsed
        .models
        .into_iter()
        .filter(|m| {
            if m.provider == CODEX_PROVIDER_ID {
                true
            } else {
                tracing::warn!(
                    "codex.json entry {}/{} has unexpected provider; dropping",
                    m.provider,
                    m.id
                );
                false
            }
        })
        .collect()
}

/// Splice the Codex seed onto an existing model list, adding entries
/// for `(provider, id)` keys not already present and leaving existing
/// entries untouched. The catalog's prior contents win on conflict so
/// a user cache that already carries refreshed Codex models doesn't
/// have its values silently rewritten by the in-process seed.
///
/// Returns the number of entries appended; useful in diagnostics and
/// tests.
pub fn splice_codex_seed(models: &mut Vec<ModelInfo>, seed: Vec<ModelInfo>) -> usize {
    if seed.is_empty() {
        return 0;
    }
    let existing: std::collections::HashSet<(String, String)> = models
        .iter()
        .map(|m| (m.provider.clone(), m.id.clone()))
        .collect();
    let mut appended = 0;
    for entry in seed {
        if existing.contains(&(entry.provider.clone(), entry.id.clone())) {
            continue;
        }
        models.push(entry);
        appended += 1;
    }
    appended
}

/// Resolve the user-cache path (`~/.aj/models.json`). Returns `None` if
/// the home directory cannot be determined.
pub fn user_cache_path() -> Option<PathBuf> {
    let mut p = home_dir()?;
    p.push(".aj");
    p.push("models.json");
    Some(p)
}

/// Local `home_dir` helper. `std::env::home_dir` was un-deprecated in
/// 1.86 but still carries the `deprecated` attribute on older toolchains
/// we want to build on; the `allow` keeps us compatible without pulling
/// in the `dirs` crate for one lookup.
fn home_dir() -> Option<PathBuf> {
    #[allow(deprecated)]
    {
        std::env::home_dir()
    }
}

/// Apply a single override entry to the model list, in place. Targets
/// that don't match any model log at debug — overrides for unreleased
/// or removed models are common during a transition.
pub(crate) fn apply_override(models: &mut [ModelInfo], entry: &OverrideEntry) {
    let Some(model) = models
        .iter_mut()
        .find(|m| m.provider == entry.target.provider && m.id == entry.target.id)
    else {
        tracing::debug!(
            "override target {}/{} not found in catalog (skipping); reason: {}",
            entry.target.provider,
            entry.target.id,
            entry.reason
        );
        return;
    };

    let p = &entry.patch;
    if let Some(v) = &p.name {
        model.name = v.clone();
    }
    if let Some(v) = &p.api {
        model.api = v.clone();
    }
    if let Some(v) = &p.base_url {
        model.base_url = v.clone();
    }
    if let Some(v) = p.reasoning {
        model.reasoning = v;
    }
    if let Some(v) = &p.reasoning_options {
        model.reasoning_options = v.clone();
    }
    if let Some(v) = p.supports_verbosity {
        model.supports_verbosity = v;
    }
    if let Some(v) = &p.input {
        model.input = v.clone();
    }
    if let Some(v) = &p.cost {
        model.cost = v.clone();
    }
    if let Some(v) = p.context_window {
        model.context_window = v;
    }
    if let Some(v) = p.max_tokens {
        model.max_tokens = v;
    }
}

